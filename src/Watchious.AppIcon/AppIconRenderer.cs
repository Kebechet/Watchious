using SkiaSharp;

namespace Watchious.AppIcon;

// Draws a WatchiousAppIcon as each platform takes an app icon. Both show the icon cut into a circle; ForegroundSize is a
// share of the width each of them shows, so the picture is as large on both.
public static class AppIconRenderer
{
    // watchOS: one opaque image, of which actool makes every size the watch needs.
    public const int WatchOSSize = 1024;

    // Wear OS: an adaptive icon's two layers are 108 dp, of which the launcher shows the middle 72 dp. They are drawn
    // at xxxhdpi (4 pixels per dp), from which Android scales them down.
    public const int WearOSLayerSize = 432;
    public const int WearOSShownSize = 288;

    public const string WearOSIconName = "appicon";

    // <catalog>/AppIcon.appiconset, the set actool compiles with --app-icon AppIcon, in an asset catalog that may hold
    // the app's other assets too.
    public static void WriteWatchOS(AppIconSettings settings, string assetCatalog)
    {
        var iconSet = Path.Combine(assetCatalog, "AppIcon.appiconset");
        Directory.CreateDirectory(iconSet);
        using var icon = DrawWatchOS(settings);
        Save(icon, Path.Combine(iconSet, "AppIcon.png"));
        File.WriteAllText(Path.Combine(iconSet, "Contents.json"), """
            {
              "images" : [
                {
                  "filename" : "AppIcon.png",
                  "idiom" : "universal",
                  "platform" : "watchos",
                  "size" : "1024x1024"
                }
              ],
              "info" : {
                "author" : "xcode",
                "version" : 1
              }
            }
            """);
        var catalogContents = Path.Combine(assetCatalog, "Contents.json");
        if (!File.Exists(catalogContents))
        {
            File.WriteAllText(catalogContents, """
                {
                  "info" : {
                    "author" : "xcode",
                    "version" : 1
                  }
                }
                """);
        }
    }

    // <res>/mipmap-anydpi-v26/appicon.xml and its two layers, which the manifest names as @mipmap/appicon.
    public static void WriteWearOS(AppIconSettings settings, string resources)
    {
        var anyDensity = Path.Combine(resources, "mipmap-anydpi-v26");
        var layers = Path.Combine(resources, "mipmap-xxxhdpi");
        Directory.CreateDirectory(anyDensity);
        Directory.CreateDirectory(layers);
        using (var background = DrawWearOSBackground(settings))
        {
            Save(background, Path.Combine(layers, $"{WearOSIconName}_background.png"));
        }

        using (var foreground = DrawWearOSForeground(settings))
        {
            Save(foreground, Path.Combine(layers, $"{WearOSIconName}_foreground.png"));
        }

        File.WriteAllText(Path.Combine(anyDensity, $"{WearOSIconName}.xml"), $"""
            <?xml version="1.0" encoding="utf-8"?>
            <!-- Generated by Kebechet.Watchious.Sdk from the app's WatchiousAppIcon. -->
            <adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
              <background android:drawable="@mipmap/{WearOSIconName}_background" />
              <foreground android:drawable="@mipmap/{WearOSIconName}_foreground" />
            </adaptive-icon>
            """);
    }

    public static SKImage DrawWatchOS(AppIconSettings settings)
    {
        var area = SKRect.Create(WatchOSSize, WatchOSSize);
        // Opaque, as the App Store requires of an icon: no alpha channel at all.
        using var surface = SKSurface.Create(new SKImageInfo(WatchOSSize, WatchOSSize, SKColorType.Rgb888x, SKAlphaType.Opaque));
        var canvas = surface.Canvas;
        canvas.Clear(SKColors.Black);
        DrawBackground(canvas, settings, area);
        DrawForeground(canvas, settings, area);
        return surface.Snapshot();
    }

    public static SKImage DrawWearOSBackground(AppIconSettings settings)
    {
        using var surface = SKSurface.Create(new SKImageInfo(WearOSLayerSize, WearOSLayerSize, SKColorType.Rgba8888, SKAlphaType.Premul));
        var canvas = surface.Canvas;
        canvas.Clear(SKColors.Black);
        // The color fills the whole layer, so no launcher's mask shows an edge; the file covers what the launcher shows,
        // as it covers the whole icon on watchOS.
        canvas.DrawColor(settings.BackgroundColor);
        DrawBackground(canvas, settings with { BackgroundColor = SKColors.Transparent }, ShownWearOSArea());
        return surface.Snapshot();
    }

    public static SKImage DrawWearOSForeground(AppIconSettings settings)
    {
        using var surface = SKSurface.Create(new SKImageInfo(WearOSLayerSize, WearOSLayerSize, SKColorType.Rgba8888, SKAlphaType.Premul));
        var canvas = surface.Canvas;
        canvas.Clear(SKColors.Transparent);
        DrawForeground(canvas, settings, ShownWearOSArea());
        return surface.Snapshot();
    }

    private static SKRect ShownWearOSArea()
    {
        var margin = (WearOSLayerSize - WearOSShownSize) / 2f;
        return SKRect.Create(margin, margin, WearOSShownSize, WearOSShownSize);
    }

    private static void DrawBackground(SKCanvas canvas, AppIconSettings settings, SKRect area)
    {
        using (var paint = new SKPaint { Color = settings.BackgroundColor })
        {
            canvas.DrawRect(area, paint);
        }

        if (settings.BackgroundFile is not null)
        {
            using var background = Artwork.Load(settings.BackgroundFile, "BackgroundFile");
            background.DrawCovering(canvas, area);
        }
    }

    private static void DrawForeground(SKCanvas canvas, AppIconSettings settings, SKRect area)
    {
        using var foreground = Artwork.Load(settings.Foreground, "Include");
        var side = area.Width * settings.ForegroundSize;
        var box = SKRect.Create(area.MidX - side / 2, area.MidY - side / 2, side, side);
        using var paint = new SKPaint { IsAntialias = true };
        if (settings.ForegroundTintColor is not null)
        {
            // Every shape of the picture in the one color, its own transparency kept.
            paint.ColorFilter = SKColorFilter.CreateBlendMode(settings.ForegroundTintColor.Value, SKBlendMode.SrcIn);
        }

        foreground.DrawInside(canvas, box, paint);
    }

    private static void Save(SKImage image, string path)
    {
        using var data = image.Encode(SKEncodedImageFormat.Png, 100);
        using var file = File.Create(path);
        data.SaveTo(file);
    }
}
